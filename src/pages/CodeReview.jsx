import { useState } from "react";
import { useNavigate } from "react-router-dom";
import "./CodeReview.css";

function CodeReview() {
  const navigate = useNavigate();

  const [code, setCode] = useState("");
  const [review, setReview] = useState("");
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

  const handleReview = async () => {
    if (!code.trim()) {
      setError("Please enter some code first.");
      return;
    }

    setLoading(true);
    setReview("");
    setError("");

    try {
      const response = await fetch(
        "http://localhost:5000/api/ai/review",
        {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
          },
          body: JSON.stringify({
            code: code,
          }),
        }
      );

      const data = await response.json();

      if (!response.ok) {
        throw new Error(data.message || "Code review failed.");
      }

      setReview(data.review);

const user = JSON.parse(localStorage.getItem("user"));

if (user?._id) {
  await fetch("http://localhost:5000/api/history", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
    },
    body: JSON.stringify({
      userId: user._id,
      type: "Code Review",
      code,
      result: data.review,
    }),
  });
}
    } catch (err) {
      setError(err.message || "Something went wrong.");
    } finally {
      setLoading(false);
    }
  };

  const handleClear = () => {
    setCode("");
    setReview("");
    setError("");
  };

  return (
    <div className="code-review-page">

      {/* Navbar */}
      <nav className="review-nav">

        <div
          className="review-logo"
          onClick={() => navigate("/dashboard")}
        >
          <span>🤖</span>
          <h1>Code Mentor AI</h1>
        </div>

        <button
          className="back-btn"
          onClick={() => navigate("/dashboard")}
        >
          ← Dashboard
        </button>

      </nav>

      {/* Main Content */}
      <main className="review-container">

        {/* Header */}
        <section className="review-header">

          <div className="review-icon">
            🔍
          </div>

          <div>
            <h2>AI Code Review</h2>

            <p>
              Paste your code below and let CodeMentor AI
              analyze it for quality, bugs, readability and improvements.
            </p>
          </div>

        </section>

        {/* Code Input Card */}
        <section className="review-card">

          <div className="card-header">

            <div>
              <h3>📝 Your Code</h3>
              <span>Paste your source code below</span>
            </div>

            <button
              className="clear-btn"
              onClick={handleClear}
              disabled={!code && !review}
            >
              Clear
            </button>

          </div>

          <textarea
            value={code}
            onChange={(e) => setCode(e.target.value)}
            placeholder={`// Paste your code here...

Example:

function add(a, b) {
    return a + b;
}`}
            spellCheck="false"
          />

          <div className="review-actions">

            <span className="code-status">
              {code.length} characters
            </span>

            <button
              className="review-btn"
              onClick={handleReview}
              disabled={loading}
            >
              {loading ? (
                <>
                  <span className="spinner"></span>
                  Reviewing...
                </>
              ) : (
                <>
                  🔍 Review Code
                </>
              )}
            </button>

          </div>

        </section>

        {/* Error */}
        {error && (
          <div className="error-message">
            ⚠️ {error}
          </div>
        )}

        {/* AI Review */}
        {review && (
          <section className="result-card">

            <div className="result-header">

              <div className="ai-title">
                <div className="ai-avatar">
                  🤖
                </div>

                <div>
                  <h3>AI Code Review</h3>
                  <span>Analysis generated by CodeMentor AI</span>
                </div>
              </div>

              <span className="success-badge">
                ✓ Completed
              </span>

            </div>

            <div className="review-result">
              {review}
            </div>

          </section>
        )}

        {/* Empty State */}
        {!review && !loading && (
          <section className="info-card">

            <div className="info-icon">
              💡
            </div>

            <div>
              <h3>What will CodeMentor AI check?</h3>

              <div className="check-list">

                <span>✓ Code quality</span>
                <span>✓ Bugs and errors</span>
                <span>✓ Performance</span>
                <span>✓ Readability</span>
                <span>✓ Best practices</span>
                <span>✓ Improvement suggestions</span>

              </div>
            </div>

          </section>
        )}

      </main>

    </div>
  );
}

export default CodeReview;