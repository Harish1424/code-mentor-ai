import { useState } from "react";
import { useNavigate } from "react-router-dom";
import "./ExplainCode.css";

function ExplainCode() {
  const navigate = useNavigate();

  const [code, setCode] = useState("");
  const [explanation, setExplanation] = useState("");
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

  const handleExplain = async () => {
    if (!code.trim()) {
      setError("Please enter some code first.");
      return;
    }

    setLoading(true);
    setExplanation("");
    setError("");

    try {
      const response = await fetch(
        "http://localhost:5000/api/ai/explain",
        {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
          },
          body: JSON.stringify({ code }),
        }
      );

      const data = await response.json();

      if (!response.ok) {
        throw new Error(
          data.message || "Code explanation failed."
        );
      }

      setExplanation(data.explanation);

const user = JSON.parse(localStorage.getItem("user"));

if (user?._id) {
  await fetch("http://localhost:5000/api/history", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
    },
    body: JSON.stringify({
      userId: user._id,
      type: "Explain Code",
      code,
      result: data.explanation,
    }),
  });
}
    } catch (err) {
      setError(err.message || "Something went wrong.");
    } finally {
      setLoading(false);
    }
  };

  const handleClear = () => {
    setCode("");
    setExplanation("");
    setError("");
  };

  return (
    <div className="explain-page">

      {/* Navbar */}
      <nav className="explain-nav">

        <div
          className="explain-logo"
          onClick={() => navigate("/dashboard")}
        >
          <span>🤖</span>
          <h1>Code Mentor AI</h1>
        </div>

        <button
          className="back-btn"
          onClick={() => navigate("/dashboard")}
        >
          ← Dashboard
        </button>

      </nav>

      <main className="explain-container">

        {/* Header */}
        <section className="explain-header">

          <div className="explain-icon">
            💡
          </div>

          <div>
            <h2>Explain Code</h2>

            <p>
              Understand complex code with simple,
              beginner-friendly explanations powered by AI.
            </p>
          </div>

        </section>

        {/* Input */}
        <section className="explain-card">

          <div className="card-header">

            <div>
              <h3>📝 Your Code</h3>

              <span>
                Paste the code you want to understand
              </span>
            </div>

            <button
              className="clear-btn"
              onClick={handleClear}
              disabled={!code && !explanation}
            >
              Clear
            </button>

          </div>

          <textarea
            value={code}
            onChange={(e) => setCode(e.target.value)}
            placeholder={`// Paste your code here...

Example:

function add(a, b) {
    return a + b;
}`}
            spellCheck="false"
          />

          <div className="explain-actions">

            <span className="code-status">
              {code.length} characters
            </span>

            <button
              className="explain-btn"
              onClick={handleExplain}
              disabled={loading}
            >
              {loading ? (
                <>
                  <span className="spinner"></span>
                  Explaining...
                </>
              ) : (
                <>
                  💡 Explain Code
                </>
              )}
            </button>

          </div>

        </section>

        {/* Error */}
        {error && (
          <div className="error-message">
            ⚠️ {error}
          </div>
        )}

        {/* Explanation */}
        {explanation && (
          <section className="explanation-card">

            <div className="result-header">

              <div className="ai-title">

                <div className="ai-avatar">
                  🤖
                </div>

                <div>
                  <h3>AI Explanation</h3>

                  <span>
                    Simple explanation generated by CodeMentor AI
                  </span>
                </div>

              </div>

              <span className="success-badge">
                ✓ Completed
              </span>

            </div>

            <div className="explanation-result">
              {explanation}
            </div>

          </section>
        )}

        {/* Info */}
        {!explanation && !loading && (

          <section className="info-card">

            <div className="info-icon">
              💡
            </div>

            <div>

              <h3>What can CodeMentor AI explain?</h3>

              <div className="check-list">

                <span>✓ Code structure</span>
                <span>✓ Functions and methods</span>
                <span>✓ Variables</span>
                <span>✓ Program flow</span>
                <span>✓ Complex logic</span>
                <span>✓ Beginner-friendly concepts</span>

              </div>

            </div>

          </section>

        )}

      </main>

    </div>
  );
}

export default ExplainCode;